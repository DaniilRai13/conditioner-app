const MAP: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh",
  з: "z", и: "i", й: "y", к: "k", л: "l", м: "m", н: "n", о: "o",
  п: "p", р: "r", с: "s", т: "t", у: "u", ф: "f", х: "h", ц: "ts",
  ч: "ch", ш: "sh", щ: "sch", ъ: "", ы: "y", ь: "", э: "e", ю: "yu",
  я: "ya",
};

/**
 * Кириллица → латиница для слагов.
 *
 * Слаги поставщика — процентно-кодированная кириллица вида
 * `%d0%ba%d0%be%d0%bd...`: нечитаемо, разваливается при копировании
 * и плохо выглядит в выдаче. Генерируем свои (PLAN.md §4).
 *
 * Слаг фиксируется при первом импорте и больше не меняется:
 * смена URL опубликованной страницы стоит позиций в поиске.
 */
export function slugify(input: string): string {
  return input
    .toLowerCase()
    .split("")
    .map((ch) => (ch in MAP ? MAP[ch] : ch))
    .join("")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);
}
