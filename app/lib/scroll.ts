/**
 * Прокрутка к элементу с оглядкой на системное «меньше движения».
 *
 * Вынесено из хука, потому что прокрутка нужна и по смене состояния
 * (результат подбора появился), и по нажатию («пройти заново»), а проверка
 * настройки движения у них одна и та же. Две копии этой проверки разошлись бы
 * на первом же изменении: одну поправят, вторую забудут.
 *
 * Мгновенно, но происходит: при «меньше движения» отменять саму прокрутку
 * нельзя — человек просто не поймёт, куда делось то, что он открыл.
 *
 * `block` по умолчанию `nearest` — минимальный сдвиг, лишь бы элемент
 * оказался целиком на экране. Для возврата это правильнее, чем `start`:
 * панель подбора живёт в первом экране рядом с заголовком, и подтягивание
 * её к самому верху срезало бы всё, что вокруг неё.
 */
export function scrollToElement(
  el: Element | null | undefined,
  block: ScrollLogicalPosition = "nearest",
): void {
  if (!el) return;

  const smooth = !window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  el.scrollIntoView({ behavior: smooth ? "smooth" : "auto", block });
}
