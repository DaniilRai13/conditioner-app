/**
 * Общая часть окружения серверных обработчиков — адрес Supabase и ключи.
 *
 * Появился, чтобы убрать дублирование. До этого адрес проекта и анонимный
 * ключ приходилось задавать дважды: `VITE_SUPABASE_URL` для браузера
 * и `SUPABASE_URL` для обработчиков, — а на хостинге это две лишние
 * переменные и лишний повод поправить в одном месте и забыть в другом.
 *
 * Дублирование было необязательным. Префикс `VITE_` управляет тем, что Vite
 * ОТДАЁТ браузеру; серверному коду он ничего не запрещает — `process.env`
 * на хостинге содержит все переменные, как их ни назови. А адрес проекта
 * и анонимный ключ и так публичны: они лежат в бандле у каждого посетителя,
 * прятать их не от кого.
 *
 * Поэтому канонические имена без префикса остаются, но если их не задали —
 * берутся публичные. Одного комплекта переменных теперь достаточно.
 *
 * Сервисного ключа это не касается и не должно: у него нет и не может быть
 * версии с префиксом. С ним он уехал бы в браузер вместе с полным доступом
 * к базе, мимо всех политик.
 */
export type SupabaseEnv = {
  /** Адрес проекта Supabase. */
  SUPABASE_URL?: string;
  /** Анонимный ключ. Публичный: лежит в бандле, защищает его RLS. */
  SUPABASE_ANON_KEY?: string;

  // Те же значения под публичными именами — их задаёт Vite для браузера.
  // Обработчики читают их как запасной вариант, чтобы на хостинге
  // не приходилось держать по две переменные на одно значение.
  VITE_SUPABASE_URL?: string;
  VITE_SUPABASE_ANON_KEY?: string;
};

/**
 * Свести публичные имена к каноническим.
 *
 * Вызывается один раз на входе обработчика, дальше код читает только
 * `SUPABASE_URL` и `SUPABASE_ANON_KEY` и о втором комплекте имён не знает.
 * Разбирать имена в каждом месте использования значило бы девять шансов
 * забыть про один из них.
 */
export function resolveSupabase<T extends SupabaseEnv>(env: T): T {
  return {
    ...env,
    SUPABASE_URL: env.SUPABASE_URL || env.VITE_SUPABASE_URL,
    SUPABASE_ANON_KEY: env.SUPABASE_ANON_KEY || env.VITE_SUPABASE_ANON_KEY,
  } as T;
}
