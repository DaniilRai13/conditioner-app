import siteData from "../data/site-data.json" with { type: "json" };

/**
 * Цифры и списки, влияющие на цену.
 *
 * Раньше они лежали прямо здесь. Теперь их ведёт заказчик в админке, а
 * scripts/fetch-data.ts на сборке складывает ответ базы в site-data.json.
 * Этот файл — тонкая обёртка над снимком: он даёт данным имена и типы,
 * которые уже разошлись по страницам, и добавляет то, что данными не
 * является, — правила показа.
 *
 * Почему обёртка, а не импорт JSON по месту: страниц, читающих прайс,
 * четыре, и каждая читает свой кусок. Пока имя одно, замена источника
 * стоит одной правки здесь; без неё пришлось бы обойти все четыре и
 * запомнить, что где называется в базе.
 */

/**
 * Наценка на оборудование. Заказчик решил продавать по цене поставщика
 * и зарабатывать на монтаже — но коэффициент вынесен, чтобы при желании
 * добавить процент правкой одного числа (PLAN.md §11).
 *
 * В базу не уехал намеренно: он применяется при выгрузке от поставщика,
 * то есть до того, как цена вообще попадает в базу. Менять его в админке
 * значило бы менять уже сохранённые числа задним числом.
 */
export const MARKUP = 1.0;

/**
 * Как показывать цену на карточке товара. Не данные, а решение о подаче:
 * "split" — цена оборудования плюс отдельная строка про монтаж,
 * "turnkey" — одно слитое «от X р. под ключ».
 *
 * Второй режим включаем, когда монтаж подтверждён и его можно складывать
 * с оборудованием, не рискуя назвать цифру, которой не будет.
 */
export const PRICE_MODE: "split" | "turnkey" = "split";

/**
 * Строки прайса на монтаж. Мощность в BTU — так их маркируют производители.
 * areaTo — та же граница числом: по ней страница цен берёт из каталога
 * «оборудование от» и строит ссылку в каталог с фильтром.
 */
export const installRows = siteData.installRows;

/**
 * Пока false — на странице цен вместо чисел стоит «по запросу».
 * Публиковать неподтверждённый прайс нельзя: клиент приедет с этой цифрой,
 * а она ничем не подтверждена.
 *
 * Считается в fetch-data.ts и требует подтверждения ВСЕХ строк: половина
 * прайса с числами и половина с «по запросу» читается так, будто часть
 * работ скрывают.
 */
export const PRICES_CONFIRMED = siteData.pricesConfirmed;

/** Состав стандартного монтажа. Один источник для всех страниц решений. */
export const STANDARD_INSTALL_INCLUDES = siteData.installIncludes;

/** Что оплачивается отдельно. Честный список снимает споры на объекте. */
export const EXTRA_CHARGES = siteData.extraCharges;

/** Срок поставки под заказ. Своего склада нет, везём под клиента. */
export const DELIVERY_DAYS = siteData.deliveryDays;

/**
 * Цена монтажа для помещения такой площади.
 *
 * Границы берём из самого прайса, а не из отдельных констант: иначе
 * заказчик добавляет в админке строку на 90 м², а функция продолжает
 * отдавать цену последней известной ей строки, и карточка товара
 * расходится со страницей цен.
 *
 * Больше самой большой строки — отдаём её цену: это «от», и занизить
 * здесь честнее, чем придумать.
 */
export function installPriceFor(areaM2: number): number {
  const row =
    installRows.find((r) => areaM2 <= r.areaTo) ??
    installRows[installRows.length - 1];

  return row?.price ?? 0;
}
