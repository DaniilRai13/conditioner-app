/**
 * Переопределение токенов на обёртке. Внутри демо написано один раз
 * и через var() — поэтому все четыре показывают буквально одну и ту же
 * вёрстку, а не четыре похожих.
 */
function vars(h: Heat): CSSProperties {
  return {
    "--heat-50": h.c50,
    "--heat-500": h.c500,
    "--heat-600": h.c600,
    "--heat-700": h.c700,
    "--heat-deep": h.deep,
  } as CSSProperties;
}

