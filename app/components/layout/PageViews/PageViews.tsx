import { useEffect, useRef } from "react";
import { useLocation } from "react-router";

/**
 * Отметка о просмотре страницы.
 *
 * Ничего не рисует. Живёт в макете публичных страниц, поэтому админка
 * в статистику не попадает — считаем посетителей, а не собственную работу.
 *
 * Переходы внутри сайта тоже считаются: React Router меняет адрес без
 * перезагрузки, и без подписки на location вся статистика состояла бы
 * из одних первых страниц, а «какие разделы смотрят» осталось бы без
 * ответа. Отсюда и ref: в режиме разработки эффекты выполняются дважды,
 * а один переход обязан давать одну отметку.
 *
 * `keepalive` ради последней страницы: человек нажимает ссылку наружу,
 * вкладка закрывается, и обычный запрос браузер отменяет. С этим флагом
 * он доживает до отправки — именно последняя страница перед уходом чаще
 * всего и есть ответ на вопрос, где человек потерялся.
 *
 * Ошибки проглатываются молча и намеренно: счётчик не должен быть заметен
 * посетителю ни при каких обстоятельствах. Упавший сервер, блокировщик
 * рекламы, отключённая сеть — всё это проблемы владельца сайта, а не
 * человека, который просто открыл страницу.
 */
export function PageViews() {
  const { pathname } = useLocation();
  const last = useRef<string | null>(null);

  useEffect(() => {
    // На localhost не считаем: иначе своя же разработка попадает в цифры
    // заказчика, и «двести посещений за вечер» оказываются сборкой.
    if (window.location.hostname === "localhost") return;
    if (last.current === pathname) return;
    last.current = pathname;

    void fetch("/api/track", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ path: pathname, ref: document.referrer }),
      keepalive: true,
    }).catch(() => {});
  }, [pathname]);

  return null;
}
