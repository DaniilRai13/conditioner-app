import type { Config } from "@react-router/dev/config";
import { dynamicPaths } from "./app/lib/sitemap";

export default {
  // Рантайм-сервера нет: сайт целиком уезжает на CDN статикой.
  // Следствие — в роутах нельзя использовать action и headers,
  // заявки уходят в отдельную serverless-функцию (см. PLAN.md §8).
  ssr: false,

  // Каталог приезжает из Supabase до того, как сборка вообще начнётся:
  // scripts/fetch-data.ts кладёт его в app/data, и дальше он читается
  // как обычный JSON. Асинхронный фетч внутри лоадеров тут не годится —
  // список слагов для пререндера нужен ещё до запуска React (PLAN.md §5.2).
  //
  // getStaticPaths() отдаёт только статические роуты. Динамические
  // (:slug) нужно перечислить руками: иначе они уедут в SPA-фолбэк
  // и потеряют пререндер, а вместе с ним и SEO.
  async prerender({ getStaticPaths }) {
    return [
      // Админку не пререндерим: она клиентская и требует входа, а статика
      // с формой логина в поисковой выдаче не нужна никому.
      //
      // /dev/ сейчас пуст, но фильтр оставлен: черновые витрины заводятся
      // и удаляются постоянно, и один раз такая страница уже уехала
      // в сборку ровно потому, что фильтр сняли вместе с последней из них.
      ...getStaticPaths().filter(
        (path) => !path.startsWith("/admin") && !path.startsWith("/dev/")
      ),
      // Динамические пути — из того же модуля, что и карта сайта:
      // так собранное и заявленное поисковику не могут разойтись.
      ...dynamicPaths(),
      "/sitemap.xml",
      "/robots.txt",
    ];
  },
} satisfies Config;
